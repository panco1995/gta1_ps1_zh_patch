def lines(raw):
    return ["" if item == "∅" else item for item in raw]


def main() -> None:
    original = r.VSR.read_bytes()
    _atad, chunks = r.walk_chunks(original)
    table, root = r.load_tree(chunks[r.EN_HUFF][1])
    import re

    spec = re.compile(r"%[0-9]*[A-Za-z]")
    out_rows = []
    for index, translated in ((0, lines(BIN0)), (6, lines(BIN6))):
        decoded = r.decode_bin(chunks[index][1], table, root)
        if len(translated) != len(decoded):
            raise SystemExit(f"bin {index} has {len(translated)} lines, game has {len(decoded)}")
        for (sid, en), zh in zip(decoded, translated):
            en_s = en.decode("latin1")
            if spec.findall(en_s) != spec.findall(zh):
                raise SystemExit(f"bin {index} id {sid} format {spec.findall(en_s)} vs {spec.findall(zh)}")
            if en_s.count("#") != zh.count("#") or en_s.count("@") != zh.count("@"):
                raise SystemExit(f"bin {index} id {sid} break counts differ")
            if len(zh.encode("utf-8")) + 1 > 198:
                raise SystemExit(f"bin {index} id {sid} is {len(zh.encode('utf-8'))} bytes")
            if not zh and en_s:
                raise SystemExit(f"bin {index} id {sid} translation is empty")
            out_rows.append((index, sid, zh, en_s))
    dest = Path(__file__).resolve().parents[1] / "text" / "zh_ui.tsv"
    with dest.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, delimiter="\t", lineterminator="\n")
        writer.writerow(["bin", "id", "zh", "en"])
        writer.writerows(out_rows)
    print(f"wrote {dest} rows {len(out_rows)}")


if __name__ == "__main__":
    main()
